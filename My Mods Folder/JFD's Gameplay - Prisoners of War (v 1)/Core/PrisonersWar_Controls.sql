UPDATE Controls
SET HotKey = null
WHERE Type IN ('CONTROL_ENDTURN', 'CONTROL_ENDTURN_ALT')
AND EXISTS (SELECT * FROM JFD_GlobalUserSettings WHERE Type = 'JFD_PRISONERS_WAR_DISABLE_CONTROLS' AND Value = 1);	
